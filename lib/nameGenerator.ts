// ============================================================
// TYPES
// ============================================================

type WordPool = readonly string[];

type TwoWordPattern = {
  type: "two-word";
  first: WordPool;
  second: WordPool;
  weight: number;
};

type ThreeWordPattern = {
  type: "three-word";
  generate: () => string;
  weight: number;
};

type SpecialPattern = {
  type: "special";
  generate: () => string;
  weight: number;
};


// ============================================================
// HELPERS
// ============================================================

function randomItem<T>(items: readonly T[]): T {
  return items[Math.floor(Math.random() * items.length)];
}

function randomFromPool(pool: WordPool): string {
  return randomItem(pool);
}

function twoWords(first: WordPool, second: WordPool): string {
  return `${randomFromPool(first)} ${randomFromPool(second)}`;
}


