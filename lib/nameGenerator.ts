// ============================================================
// WEIGHTED RANDOM SELECTION
// ============================================================

type Pattern = TwoWordPattern | ThreeWordPattern | SpecialPattern;

function selectWeightedPattern<T extends Pattern>(patterns: T[]): T {
  const totalWeight = patterns.reduce(
    (total, pattern) => total + pattern.weight,
    0
  );

  let random = Math.random() * totalWeight;

  for (const pattern of patterns) {
    random -= pattern.weight;

    if (random <= 0) {
      return pattern;
    }
  }

  return patterns[patterns.length - 1];
}


// ============================================================
// GENERATE NAME
// ============================================================

export function generateRandomName(previousName?: string): string {
  let name = "";

  // 75% → normal 2-word names
  // 10% → 3-word names
  // 15% → special names

  const roll = Math.random();

  if (roll < 0.75) {
    const pattern = selectWeightedPattern(twoWordPatterns);

    name = twoWords(pattern.first, pattern.second);
  } else if (roll < 0.85) {
    const pattern = selectWeightedPattern(threeWordPatterns);

    name = pattern.generate();
  } else {
    const pattern = selectWeightedPattern(specialPatterns);

    name = pattern.generate();
  }

  // Prevent immediate duplicate
  if (name === previousName) {
    return generateRandomName(previousName);
  }

  return name;
}